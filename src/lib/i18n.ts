// Interface languages, modelled on Hyper's Gallery: Chinese at the root,
// English under /en/, Japanese under /ja/. Only the interface is translated;
// post titles and content stay as written.
export const LOCALES = ['zh', 'en', 'ja'] as const;
export type Lang = (typeof LOCALES)[number];

export const LANG_META: Record<Lang, { html: string; prefix: string; label: string }> = {
  zh: { html: 'zh-CN', prefix: '', label: '中文' },
  en: { html: 'en', prefix: '/en', label: 'English' },
  ja: { html: 'ja', prefix: '/ja', label: '日本語' },
};

export function getLang(url: URL): Lang {
  const seg = decodeURI(url.pathname).split('/')[1];
  return seg === 'en' || seg === 'ja' ? seg : 'zh';
}

/** Path without the language prefix, always starting with "/". */
export function stripLang(pathname: string): string {
  const m = pathname.match(/^\/(en|ja)(\/.*)?$/);
  return m ? m[2] || '/' : pathname;
}

/** Localise an internal path for a language. */
export const l = (lang: Lang, path: string) => LANG_META[lang].prefix + path;

