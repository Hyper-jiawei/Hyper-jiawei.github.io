type Key = keyof (typeof dict)['zh'];

/** Translator for a language; `{name}` placeholders are filled from vars. */
export function useT(lang: Lang) {
  const table = dict[lang] as Record<Key, unknown>;
  function t(key: Key, vars: Record<string, string | number> = {}): string {
    const raw = table[key] as string;
    return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
  }
  t.list = (key: Key) => table[key] as readonly string[];
  return t;
}

/** Everything a component needs, from the current URL. */
export function i18n(url: URL) {
  const lang = getLang(url);
  return { lang, t: useT(lang), l: (path: string) => l(lang, path) };
}
