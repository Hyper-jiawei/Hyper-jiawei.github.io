export interface Dot { x: number; y: number; on: boolean; accent: boolean; /** glyph index */ g: number }

/** Lays text out on the dot grid. `accent` chars (by index) are flagged for colouring. */
export function layout(text: string, accentFrom = Infinity, rows: 7 | 8 = 8) {
  const dots: Dot[] = [];
  let x = 0;
  [...text].forEach((ch, i) => {
    const g = GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS['?'];
    const w = g[0].length;
    for (let y = 0; y < rows; y++)
      for (let c = 0; c < w; c++) dots.push({ x: x + c, y, on: g[y][c] === '1', accent: i >= accentFrom, g: i });
    x += w + 1;
  });
  return { dots, width: Math.max(1, x - 1), height: rows };
}
