// A 5×7 dot-matrix font (HD44780-style) with an 8th row for descenders.
// Each glyph is a list of rows; '1' = lit dot. Glyphs may be narrower than 5.

const R = (...rows: string[]) => {
  const w = Math.max(...rows.map((r) => r.length));
  const out = rows.map((r) => r.padEnd(w, '0'));
  while (out.length < 8) out.push('0'.repeat(w));
  return out;
};

